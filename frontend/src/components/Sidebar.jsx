const navItems = [
  { path: '/', label: 'Dashboard', icon: icons.dashboard, exact: true },
  { path: '/tasks', label: 'My Tasks', icon: icons.tasks },
  { path: '/tasks?status=completed', label: 'Completed', icon: icons.completed },
];

export default function Sidebar({ user }) {
  const location = useLocation();

  const isActive = (path, exact = false) => {
    if (exact) {
      return location.pathname === path;
    }
    return location.pathname.startsWith(path.replace('?status=completed', ''));
  };

  return (
    <aside className="sidebar">
      <div className="sidebar-brand">
        <div className="sidebar-brand-icon">T</div>
        <span className="sidebar-brand-text">TaskFlow</span>
      </div>

      <nav className="sidebar-nav" aria-label="Main navigation">
        <div className="sidebar-nav-section">Overview</div>
        {navItems.map((item) => (
          <NavLink
            key={item.path}
            to={item.path}
            className={({ isActive: isActiveLink }) =>
              `sidebar-link ${isActiveLink || isActive(item.path, item.exact) ? 'active' : ''}`
            }
            end={item.exact}
          >
            {item.icon}
            {item.label}
          </NavLink>
        ))}
      </nav>

      <div className="sidebar-footer">
        {user && (
          <div style={{ padding: 'var(--space-3)', marginBottom: 'var(--space-2)' }}>
            <div className="avatar" aria-hidden="true">
              {user.name?.charAt(0) || user.email?.charAt(0) || 'U'}
            </div>
          </div>
        )}
        <NavLink to="/login" className="sidebar-link">
          {icons.logout}
          {user ? 'Sign out' : 'Sign in'}
        </NavLink>
      </div>
    </aside>
  );
}
